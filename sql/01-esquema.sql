CREATE DATABASE IF NOT EXISTS streetfighter
    COLLATE utf8mb4_0900_ai_ci;

USE streetfighter;


CREATE TABLE IF NOT EXISTS LUCHADOR (
    Id_Luchador   INT UNSIGNED      NOT NULL AUTO_INCREMENT,
    Nombre        VARCHAR(30)       NOT NULL,
    Edad          TINYINT UNSIGNED  NULL,               -- años
    Nacionalidad  VARCHAR(40)       NULL,
    Estatura      SMALLINT UNSIGNED NULL,               -- centímetros
    Peso          SMALLINT UNSIGNED NULL,               -- kilos
    Potencia      TINYINT UNSIGNED  NOT NULL,
    Velocidad     TINYINT UNSIGNED  NOT NULL,
    Fisico        TINYINT UNSIGNED  NOT NULL,
    Descripcion   TEXT              NOT NULL,
    CONSTRAINT PK_LUCHADOR PRIMARY KEY (Id_Luchador),
    CONSTRAINT UQ_LUCHADOR_NOMBRE UNIQUE (Nombre),
    CONSTRAINT CK_LUCHADOR_POTENCIA  CHECK (Potencia  BETWEEN 1 AND 100),
    CONSTRAINT CK_LUCHADOR_VELOCIDAD CHECK (Velocidad BETWEEN 1 AND 100),
    CONSTRAINT CK_LUCHADOR_FISICO    CHECK (Fisico    BETWEEN 1 AND 100)
) ENGINE = InnoDB;


CREATE TABLE IF NOT EXISTS USUARIO (
    Id_Usuario      INT UNSIGNED NOT NULL AUTO_INCREMENT,
    Nombre          VARCHAR(30)  NOT NULL,
    Contrasenia      VARCHAR(255) NOT NULL,              -- hash, nunca texto plano
    Total_Victorias INT UNSIGNED NOT NULL DEFAULT 0,
    Total_Derrotas  INT UNSIGNED NOT NULL DEFAULT 0,
    CONSTRAINT PK_USUARIO PRIMARY KEY (Id_Usuario),
    CONSTRAINT UQ_USUARIO_NOMBRE UNIQUE (Nombre)
) ENGINE = InnoDB;

CREATE TABLE IF NOT EXISTS DESBLOQUEO (
    Id_Luchador INT UNSIGNED NOT NULL,
    Id_Usuario  INT UNSIGNED NOT NULL,
    Victorias   INT UNSIGNED NOT NULL DEFAULT 0,
    Derrotas    INT UNSIGNED NOT NULL DEFAULT 0,
    CONSTRAINT PK_DESBLOQUEO PRIMARY KEY (Id_Luchador, Id_Usuario),
    CONSTRAINT FK_DESBLOQUEO_LUCHADOR FOREIGN KEY (Id_Luchador)
        REFERENCES LUCHADOR (Id_Luchador)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT FK_DESBLOQUEO_USUARIO FOREIGN KEY (Id_Usuario)
        REFERENCES USUARIO (Id_Usuario)
        ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE = InnoDB;

CREATE INDEX IX_DESBLOQUEO_USUARIO ON DESBLOQUEO (Id_Usuario);
